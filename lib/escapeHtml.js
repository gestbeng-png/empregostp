/**
 * Escapa uma string para interpolação segura em HTML de email.
 *
 * Estava duplicada em seis ficheiros; passa a viver aqui.
 */
export function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export default escapeHtml;
